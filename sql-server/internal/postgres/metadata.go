package postgres

import (
	"context"
	"errors"
	"strings"

	"sqldesk/internal/model"
)

func (c *Client) Databases(ctx context.Context, connection model.Connection) ([]string, error) {
	conn, err := Open(ctx, connection, "", "")
	if err != nil {
		return nil, err
	}
	defer conn.Close(context.Background())
	rows, err := conn.Query(ctx, "SELECT datname FROM pg_database WHERE datallowconn AND NOT datistemplate AND has_database_privilege(datname,'CONNECT') ORDER BY datname")
	if err != nil {
		return nil, err
	}
	defer rows.Close()
	out := []string{}
	for rows.Next() {
		var name string
		if err = rows.Scan(&name); err != nil {
			return nil, err
		}
		out = append(out, name)
	}
	return out, rows.Err()
}

func (c *Client) Tables(ctx context.Context, connection model.Connection, database string) ([]model.Table, error) {
	conn, err := Open(ctx, connection, database, "")
	if err != nil {
		return nil, err
	}
	defer conn.Close(context.Background())
	rows, err := conn.Query(ctx, `SELECT n.nspname,c.relname,CASE WHEN c.relkind='v' THEN 'VIEW' WHEN c.relkind='m' THEN 'MATERIALIZED VIEW' ELSE 'BASE TABLE' END,COALESCE(obj_description(c.oid),'') FROM pg_class c JOIN pg_namespace n ON n.oid=c.relnamespace WHERE c.relkind IN ('r','p','v','m','f') AND n.nspname NOT IN ('pg_catalog','information_schema') AND n.nspname NOT LIKE 'pg_%' ORDER BY n.nspname,c.relname`)
	if err != nil {
		return nil, err
	}
	defer rows.Close()
	out := []model.Table{}
	for rows.Next() {
		var table model.Table
		if err = rows.Scan(&table.Schema, &table.Name, &table.Type, &table.Comment); err != nil {
			return nil, err
		}
		out = append(out, table)
	}
	return out, rows.Err()
}

func (c *Client) Columns(ctx context.Context, connection model.Connection, ref model.TableRef) ([]model.Column, error) {
	conn, err := Open(ctx, connection, ref.Database, "")
	if err != nil {
		return nil, err
	}
	defer conn.Close(context.Background())
	rows, err := conn.Query(ctx, `SELECT a.attname,format_type(a.atttypid,a.atttypmod),CASE WHEN a.attnotnull THEN 'NO' ELSE 'YES' END,
 CASE WHEN EXISTS(SELECT 1 FROM pg_index i WHERE i.indrelid=c.oid AND i.indisprimary AND a.attnum=ANY(i.indkey)) THEN 'PRI' WHEN EXISTS(SELECT 1 FROM pg_index i WHERE i.indrelid=c.oid AND a.attnum=ANY(i.indkey)) THEN 'MUL' ELSE '' END,
 pg_get_expr(d.adbin,d.adrelid),
 CASE WHEN to_jsonb(a)->>'attidentity'='a' THEN 'GENERATED ALWAYS AS IDENTITY' WHEN to_jsonb(a)->>'attidentity'='d' THEN 'GENERATED BY DEFAULT AS IDENTITY' WHEN to_jsonb(a)->>'attgenerated'='s' THEN 'GENERATED ALWAYS AS ('||pg_get_expr(d.adbin,d.adrelid)||') STORED' ELSE '' END,
 COALESCE(col_description(c.oid,a.attnum),'')
 FROM pg_attribute a JOIN pg_class c ON c.oid=a.attrelid JOIN pg_namespace n ON n.oid=c.relnamespace LEFT JOIN pg_attrdef d ON d.adrelid=c.oid AND d.adnum=a.attnum WHERE n.nspname=$1 AND c.relname=$2 AND a.attnum>0 AND NOT a.attisdropped ORDER BY a.attnum`, tableSchema(ref), ref.Name)
	if err != nil {
		return nil, err
	}
	defer rows.Close()
	out := []model.Column{}
	for rows.Next() {
		var column model.Column
		if err = rows.Scan(&column.Name, &column.Type, &column.Nullable, &column.Key, &column.Default, &column.Extra, &column.Comment); err != nil {
			return nil, err
		}
		out = append(out, column)
	}
	return out, rows.Err()
}

// DDL 为表生成字段、约束和独立索引定义；视图使用 pg_get_viewdef，不作为 pg_dump 的替代。
func (c *Client) DDL(ctx context.Context, connection model.Connection, ref model.TableRef) (string, error) {
	conn, err := Open(ctx, connection, ref.Database, "")
	if err != nil {
		return "", err
	}
	defer conn.Close(context.Background())
	var kind string
	var oid uint32
	if err = conn.QueryRow(ctx, `SELECT c.relkind::text,c.oid FROM pg_class c JOIN pg_namespace n ON n.oid=c.relnamespace WHERE n.nspname=$1 AND c.relname=$2`, tableSchema(ref), ref.Name).Scan(&kind, &oid); err != nil {
		return "", err
	}
	name := quoteIdentifier(tableSchema(ref)) + "." + quoteIdentifier(ref.Name)
	if kind == "v" || kind == "m" {
		var definition string
		if err = conn.QueryRow(ctx, "SELECT pg_get_viewdef($1::oid,true)", oid).Scan(&definition); err != nil {
			return "", err
		}
		prefix := "CREATE VIEW "
		if kind == "m" {
			prefix = "CREATE MATERIALIZED VIEW "
		}
		return prefix + name + " AS\n" + definition, nil
	}
	columns, err := c.Columns(ctx, connection, ref)
	if err != nil {
		return "", err
	}
	if len(columns) == 0 {
		return "", errors.New("未找到表字段")
	}
	parts := []string{}
	for _, column := range columns {
		line := "  " + quoteIdentifier(column.Name) + " " + column.Type
		if column.Extra != "" {
			line += " " + column.Extra
		} else if column.Default != nil {
			line += " DEFAULT " + *column.Default
		}
		if column.Nullable == "NO" {
			line += " NOT NULL"
		}
		parts = append(parts, line)
	}
	rows, err := conn.Query(ctx, "SELECT conname,pg_get_constraintdef(oid,true) FROM pg_constraint WHERE conrelid=$1::oid ORDER BY conname", oid)
	if err != nil {
		return "", err
	}
	for rows.Next() {
		var constraint, definition string
		if err = rows.Scan(&constraint, &definition); err != nil {
			rows.Close()
			return "", err
		}
		parts = append(parts, "  CONSTRAINT "+quoteIdentifier(constraint)+" "+definition)
	}
	err = rows.Err()
	rows.Close()
	if err != nil {
		return "", err
	}
	ddl := "CREATE TABLE " + name + " (\n" + strings.Join(parts, ",\n") + "\n);"
	rows, err = conn.Query(ctx, `SELECT pg_get_indexdef(i.indexrelid) FROM pg_index i WHERE i.indrelid=$1::oid AND NOT EXISTS(SELECT 1 FROM pg_constraint c WHERE c.conindid=i.indexrelid) ORDER BY i.indexrelid`, oid)
	if err != nil {
		return "", err
	}
	defer rows.Close()
	for rows.Next() {
		var definition string
		if err = rows.Scan(&definition); err != nil {
			return "", err
		}
		ddl += "\n\n" + definition + ";"
	}
	return ddl, rows.Err()
}
