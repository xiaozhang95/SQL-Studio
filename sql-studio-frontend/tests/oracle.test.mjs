import assert from 'node:assert/strict'
import test from 'node:test'

import { prepareDump } from '../src/databases/oracle/dataDump/index.ts'
import { updateRowSQL } from '../src/databases/oracle/dataEditing/index.ts'
import { tableDataSQL, tableIdentity } from '../src/databases/oracle/query/index.ts'
import { cleanOracleHistory, splitOracleStatements } from '../src/databases/oracle/statements/index.ts'

test('keeps q literals and PL/SQL blocks intact in a mixed script', () => {
  const sql = "SELECT q'[semi; -- quote'' /]' AS A FROM DUAL;\nBEGIN\n  NULL;\nEND;\n/\nSELECT 2 / 1 FROM DUAL;"
  const [first, block, last] = splitOracleStatements(sql)
  assert.equal(first, "SELECT q'[semi; -- quote'' /]' AS A FROM DUAL")
  assert.equal(block, 'BEGIN\n  NULL;\nEND;')
  assert.equal(last, 'SELECT 2 / 1 FROM DUAL')
  assert.deepEqual(splitOracleStatements(cleanOracleHistory(block) + '\n' + cleanOracleHistory(last)), [block, last])
})

test('rejects an incomplete script before submitting any statement', () => {
  for (const tail of ["SELECT q'[incomplete", '/* incomplete', 'SELECT "incomplete']) {
    assert.throws(() => splitOracleStatements('SELECT 1 FROM DUAL;\n' + tail), /未闭合/)
  }
})

test('uses complete schema identity and keeps NUMBER exact on a grid update', () => {
  const table = '"Mixed.Schema"."Order Details"'
  assert.deepEqual(tableIdentity(table), { schema: 'Mixed.Schema', name: 'Order Details' })
  assert.equal(tableDataSQL('', table), 'SELECT * FROM "Mixed.Schema"."Order Details" FETCH FIRST 1000 ROWS ONLY;')
  const columns = [
    { name: 'ID', type: 'NUMBER(38,0)', key: 'PRI' },
    { name: 'CUSTOMER', type: 'VARCHAR2(100 CHAR)', nullable: 'YES', extra: '' }
  ]
  const result = {
    columns: [
      { name: 'ID', type: 'NUMBER' },
      { name: 'CUSTOMER', type: 'VARCHAR2' }
    ]
  }
  assert.equal(
    updateRowSQL('', table, columns, result, ['98765432109876543210987654321098765432', 'Old'], [{ columnIndex: 1, value: "O'Brien" }]),
    `UPDATE ${table} SET "CUSTOMER" = 'O''Brien' WHERE "ID" = 98765432109876543210987654321098765432 AND "CUSTOMER" = 'Old';`
  )
})

test('defers dump foreign keys and preserves generated columns and binary values', () => {
  const table = '"APP"."T"'
  const ddl = `CREATE TABLE ${table} ("ID" NUMBER, "B" BLOB, "V" NUMBER GENERATED ALWAYS AS (1) VIRTUAL);
ALTER TABLE ${table} ADD CONSTRAINT "FK" FOREIGN KEY ("ID") REFERENCES "APP"."P" ("ID");`
  const columns = [
    { name: 'ID', type: 'NUMBER', extra: 'GENERATED ALWAYS AS IDENTITY' },
    { name: 'B', type: 'BLOB', extra: '' },
    { name: 'V', type: 'NUMBER', extra: 'GENERATED VIRTUAL' }
  ]
  const plan = prepareDump('FREEPDB1', table, ddl, columns, undefined, true)
  assert.match(plan.before, /GENERATED BY DEFAULT AS IDENTITY/)
  assert.doesNotMatch(plan.before, /FOREIGN KEY/)
  assert.match(plan.constraints, /FOREIGN KEY/)
  assert.match(plan.after, /START WITH LIMIT VALUE/)
  const sql = plan.data({ columns, rows: [['9007199254740993', '0x00ff', '1']] })
  assert.match(sql, /"ID", "B"\) VALUES \(9007199254740993, EMPTY_BLOB\(\)\)/)
  assert.match(sql, /DBMS_LOB\.WRITEAPPEND\(lob1, 2, HEXTORAW\('00ff'\)\)/)
  assert.equal(splitOracleStatements(sql).length, 1)
})
