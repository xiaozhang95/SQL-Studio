test('PostgreSQL object operations preserve schema and quote names', () => {
  const target = { connectionId: 'c', database: 'db', table: '"a.b"."old"', view: false }
  assert.equal(simpleObjects.sql(ObjectAction.CreateDatabase, target, 'a"b'), 'CREATE DATABASE "a""b";')
  assert.equal(simpleObjects.sql(ObjectAction.DropDatabase, target, ''), 'DROP DATABASE "db";')
  assert.equal(simpleObjects.sql(ObjectAction.DropTable, target, ''), 'DROP TABLE "a.b"."old";')
  assert.equal(simpleObjects.sql(ObjectAction.TruncateTable, target, ''), 'TRUNCATE TABLE "a.b"."old";')
  assert.equal(simpleObjects.sql(ObjectAction.RenameTable, { ...target, view: true }, 'new"name'), 'ALTER VIEW "a.b"."old" RENAME TO "new""name";')
  assert.equal(simpleObjects.resultName(ObjectAction.RenameTable, target, 'new"name'), '"a.b"."new""name"')
  assert.throws(() => simpleObjects.sql(ObjectAction.CreateDatabase, target, '界'.repeat(22)))
  assert.throws(() => simpleObjects.sql(ObjectAction.TruncateTable, { ...target, view: true }, ''))
  assert.equal(simpleObjects.sql(ObjectAction.CreateSchema, target, 'a"b'), 'CREATE SCHEMA "a""b";')
  assert.equal(simpleObjects.sql(ObjectAction.RenameSchema, { ...target, schema: 'a.b' }, 'new"name'), 'ALTER SCHEMA "a.b" RENAME TO "new""name";')
  assert.equal(simpleObjects.sql(ObjectAction.DropSchema, { ...target, schema: 'a.b' }, ''), 'DROP SCHEMA "a.b" RESTRICT;')
  assert.throws(() => simpleObjects.sql(ObjectAction.RenameSchema, { ...target, schema: 'a.b' }, 'a.b'))
  assert.throws(() => simpleObjects.sql(ObjectAction.DropSchema, target, ''))
  assert.throws(() => simpleObjects.sql(ObjectAction.EditTable, target, ''))
})

test('PostgreSQL table design uses schema and preserves existing fields', () => {
  const target = { connectionId: 'c', database: 'db', schema: 'a.b', table: '"a.b"."t"' }
  const values = { name: 'new"table', charset: '', collation: '', confirmation: '', fields: tableDesign.initialFields() }
  assert.match(tableDesign.sql(ObjectAction.CreateTable, target, values, []), /CREATE TABLE "a\.b"\."new""table"/)
  assert.match(tableDesign.sql(ObjectAction.CreateTable, target, values, []), /GENERATED BY DEFAULT AS IDENTITY/)
  assert.equal(tableDesign.identity(target, values.name), '"a.b"."new""table"')
  assert.throws(() => tableDesign.identity({ ...target, schema: '' }, values.name))
  const original = tableDesign.fields([{ name: 'id', type: 'bigint', nullable: 'NO', key: 'PRI', default: null, extra: '', comment: '' }])
  const added = { ...tableDesign.defaultField(), name: 'new_col' }
  assert.equal(tableDesign.sql(ObjectAction.EditTable, target, { ...values, fields: [...original, added] }, original), 'ALTER TABLE "a.b"."t" ADD COLUMN "new_col" text;')
  assert.match(tableDesign.sql(ObjectAction.EditTable, target, { ...values, fields: [{ ...original[0], type: 'text' }, added] }, original), /ALTER COLUMN.*TYPE text/)
  assert.throws(() => tableDesign.sql(ObjectAction.EditTable, target, { ...values, fields: [...original, { ...added, type: 'text; DROP TABLE x' }] }, original))
})

test('PostgreSQL designer applies edits and comments atomically and preserves unchanged defaults', () => {
  const target = { connectionId: 'c', database: 'db', schema: 's', table: '"s"."t"' }
  const original = tableDesign.fields([
    { name: 'id', type: 'integer', nullable: 'NO', key: 'PRI', default: null, extra: 'IDENTITY', comment: '' },
    { name: 'value', type: 'text', nullable: 'YES', key: '', default: "'old'::text", extra: '', comment: 'old' }
  ])
  assert.equal(original[0].autoIncrement, true)
  assert.equal(original[1].defaultValue, "'old'::text")
  const values = { name: 't', charset: '', collation: '', confirmation: '', fields: [original[0], { ...original[1], name: 'v"2', nullable: false, comment: "x'$sql_studio$" }] }
  const sql = tableDesign.sql(ObjectAction.EditTable, target, values, original)
  assert.match(sql, /RENAME COLUMN/)
  assert.match(sql, /SET NOT NULL/)
  assert.match(sql, /COMMENT ON COLUMN/)
  assert.doesNotMatch(sql, /SET DEFAULT/)
  assert.equal(splitPostgreSQLStatements(sql).length, 1)
  const primary = tableDesign.sql(
    ObjectAction.EditTable,
    target,
    {
      ...values,
      fields: [
        { ...original[0], primary: false },
        { ...original[1], primary: true, nullable: false }
      ]
    },
    original
  )
  assert.match(primary, /pg_catalog\.pg_constraint/)
  assert.match(primary, /ADD PRIMARY KEY/)
  assert.equal(splitPostgreSQLStatements(primary).length, 1)
  assert.throws(() => tableDesign.sql(ObjectAction.EditTable, target, { ...values, fields: [original[0], { ...original[1], defaultValue: '1; DROP TABLE t' }] }, original))
})

test('PostgreSQL splitter handles dollar bodies, nested comments, E strings and standard strings', () => {
  const body = "DO $body$ BEGIN RAISE NOTICE 'a;b'; END; $body$;"
  assert.deepEqual(splitPostgreSQLStatements(body + ' SELECT 1;'), [body, 'SELECT 1;'])
  assert.deepEqual(splitPostgreSQLStatements("/* outer /* nested ; */ end */ SELECT E'a\\\';b'; SELECT 2;"), ["/* outer /* nested ; */ end */ SELECT E'a\\\';b';", 'SELECT 2;'])
  assert.deepEqual(splitPostgreSQLStatements("SELECT 'a\\'; SELECT 2;"), ["SELECT 'a\\';", 'SELECT 2;'])
  assert.deepEqual(splitPostgreSQLStatements('SELECT "a;b";--no space;\nSELECT 2;'), ['SELECT "a;b";', '--no space;\nSELECT 2;'])
  assert.deepEqual(splitPostgreSQLStatements('-- comment\n/* nested /* ; */ */;'), [])
  for (const input of ["SELECT 'unfinished", 'DO $$ missing;', '/* a /* b */']) assert.throws(() => splitPostgreSQLStatements(input))
})

test('history markers inside dollar bodies remain intact', () => {
  const body = 'DO $$\n-- 历史记录\nSELECT 1;\n$$;'
  assert.equal(cleanPostgreSQLHistory('-- 历史记录\n' + body), body)
  assert.equal(cleanPostgreSQLHistory('/* nested /* x */\n-- 历史记录\n*/\nSELECT 1'), '/* nested /* x */\n-- 历史记录\n*/\nSELECT 1')
})

test('schema qualified identifiers preserve dots/quotes and cannot inject SQL', () => {
  assert.deepEqual(tableIdentity('"a.b"."t"";x"'), ['a.b', 't";x'])
  assert.equal(relation('"a.b"."t"";x"'), '"a.b"."t"";x"')
  assert.equal(tableDataSQL('physical_database', '"other"."same"'), 'SELECT * FROM "other"."same" LIMIT 1000;')
  assert.throws(() => relation('"a"."b"; DROP TABLE x;'))
  assert.equal(relation('t; DROP TABLE x;'), '"public"."t; DROP TABLE x;"')
  assert.equal(literal("a'\\b"), "E'a''\\\\b'")
  assert.throws(() => literal('a\0b'))
  assert.doesNotMatch(exportDDL('db', 't', 'CREATE TABLE t(id int);'), /USE /)
})

const columns = [
  { name: 'id', type: 'bigint', key: 'PRI', nullable: 'NO', default: null, extra: '' },
  { name: 'value', type: 'text', key: '', nullable: 'YES', default: null, extra: '' }
]
const result = { columns: [{ name: 'id' }, { name: 'value' }] }
test('PostgreSQL data editing uses explicit schema and complete primary key with optimistic value check', () => {
  const sql = updateCellSQL('db', '"a"."t"', columns, result, ['9007199254740993', null], 1, "x'y")
  assert.equal(sql, `UPDATE "a"."t" SET "value" = E'x''y' WHERE "id" IS NOT DISTINCT FROM E'9007199254740993' AND "value" IS NOT DISTINCT FROM NULL;`)
  assert.throws(() => updateCellSQL('db', 't', columns, { columns: [{ name: 'value' }] }, ['v'], 0, 'new'))
  assert.equal(insertRowSQL('db', '"a"."t"', columns, result, ['1', null]), `INSERT INTO "a"."t" ("id", "value") VALUES (E'1', NULL);`)
  assert.throws(() => insertRowSQL('db', 't', columns, result, [undefined, 'v']))
})

