import type { Column, QueryResult } from '../../../typings/database/index.ts'
import type { DumpPlan } from '../../typings/index.ts'
import { sqlValue } from '../dataEditing/index.ts'
import { identifier, relation, tableDataSQL, textLiteral } from '../query/index.ts'
import { oracleTokens, splitOracleStatements } from '../statements/index.ts'

const utf8 = new TextEncoder()

function chunks(value: string) {
  const output: string[] = []
  let piece = '',
    bytes = 0
  for (const char of value) {
    const length = utf8.encode(char).length
    if (bytes + length > 2000) {
      output.push(piece)
      piece = ''
      bytes = 0
    }
    piece += char
    bytes += length
  }
  output.push(piece)
  return output
}

function clob(type: string, value: string) {
  const national = type === 'NCLOB'
  const convert = national ? 'TO_NCLOB' : 'TO_CLOB'
  if (!value) return national ? 'TO_NCLOB(EMPTY_CLOB())' : 'EMPTY_CLOB()'
  return chunks(value)
    .map((part) => convert + '(' + (national ? 'N' : '') + textLiteral(part) + ')')
    .join(' || ')
}

function rowsSQL(table: string, columns: Column[], result: QueryResult) {
  const picked = result.columns.map((field, index) => ({ index, column: columns.find(({ name }) => name === field.name) }))
  if (picked.some(({ column }) => !column)) throw new Error('转储字段与表结构不一致')
  return result.rows
    .map((row) => {
      const names: string[] = [],
        values: string[] = [],
        lobs: { name: string; hex: string }[] = []
      for (const { column, index } of picked) {
        if (!column || column.extra.includes('VIRTUAL')) continue
        const value = row[index]
        const name = identifier(column.name)
        names.push(name)
        if (value === null) values.push('NULL')
        else if (column.type === 'BLOB') {
          if (typeof value !== 'string' || !/^0x(?:[0-9a-f]{2})*$/i.test(value)) throw new Error('Oracle BLOB 转储值无效')
          values.push('EMPTY_BLOB()')
          if (value.length > 2) lobs.push({ name, hex: value.slice(2) })
        } else if (column.type === 'CLOB' || column.type === 'NCLOB') {
          if (typeof value !== 'string' || value.includes('\0')) throw new Error('Oracle 大文本含无法写入脚本的值')
          values.push(clob(column.type, value))
        } else if (column.type === 'JSON' && typeof value === 'string' && !value.includes('\0') && utf8.encode(value).length <= 4000) {
          values.push(`JSON(${textLiteral(value)})`)
        } else values.push(sqlValue(column.type, value))
      }
      if (!names.length) throw new Error('Oracle 表没有可转储的写入字段')
      const insert = `INSERT INTO ${table} (${names.join(', ')}) VALUES (${values.join(', ')})`
      if (!lobs.length) return insert + ';\n'
      const variables = lobs.map((_, i) => 'lob' + (i + 1))
      const writes = lobs.flatMap(({ hex }, i) => (hex.match(/.{1,4000}/g) ?? []).map((part) => `  DBMS_LOB.WRITEAPPEND(${variables[i]}, ${part.length / 2}, HEXTORAW('${part}'));`))
      return [
        'DECLARE',
        ...variables.map((name) => `  ${name} BLOB;`),
        'BEGIN',
        `  ${insert} RETURNING ${lobs.map(({ name }) => name).join(', ')} INTO ${variables.join(', ')};`,
        ...writes,
        'END;',
        '/',
        ''
      ].join('\n')
    })
    .join('')
}

export function prepareDump(_database: string, table: string, ddl: string, columns: Column[], _metadata: QueryResult | undefined, withData: boolean): DumpPlan {
  const target = relation(table)
  const before: string[] = [],
    constraints: string[] = [],
    after: string[] = []
  for (const statement of splitOracleStatements(ddl)) {
    const words = Array.from(oracleTokens(statement))
      .filter((token) => token.kind === 'word')
      .map(({ text }) => text)
    const foreignKey = words[0] === 'ALTER' && words[1] === 'TABLE' && words.some((word, i) => word === 'FOREIGN' && words[i + 1] === 'KEY')
    ;(foreignKey ? constraints : before).push(statement + ';')
  }
  if (withData) {
    for (const column of columns) {
      if (!column.extra.includes('IDENTITY')) continue
      const field = identifier(column.name)
      const mode = column.extra.includes('ALWAYS') ? 'ALWAYS' : column.extra.includes('ON NULL') ? 'BY DEFAULT ON NULL' : 'BY DEFAULT'
      if (mode === 'ALWAYS') before.push(`ALTER TABLE ${target} MODIFY (${field} GENERATED BY DEFAULT AS IDENTITY);`)
      after.push(`ALTER TABLE ${target} MODIFY (${field} GENERATED ${mode} AS IDENTITY (START WITH LIMIT VALUE));`)
    }
  }
  const block = (statements: string[]) => (statements.length ? statements.join('\n') + '\n\n' : '')
  return { before: block(before), after: block(after), constraints: block(constraints), data: (result) => rowsSQL(target, columns, result) }
}

export const dataDump = {
  querySQL: (database: string, table: string) => tableDataSQL(database, table, { preview: false }),
  dump(database: string, table: string, ddl: string, result: QueryResult, columns: Column[]) {
    if (result.truncated) throw new Error('结果不完整，请使用流式转储')
    const plan = prepareDump(database, table, ddl, columns, undefined, true)
    return plan.before + plan.data(result) + plan.after + (plan.constraints ?? '')
  }
}
