import type { Column } from '../../../typings/database/index.ts'
import { ObjectAction } from '../../typings/objectManagement/index.ts'
import type { ObjectAction as Action, FieldDefinition, ObjectFormValues, ObjectTarget, TableDesignAdapter } from '../../typings/objectManagement/index.ts'
import { generated, sqlValue } from '../dataEditing/index.ts'
import { identifier, relation, textLiteral } from '../query/index.ts'

const fieldTypes = [
  'NUMBER',
  'NUMBER(18,0)',
  'NUMBER(18,2)',
  'VARCHAR2(255 CHAR)',
  'NVARCHAR2(255)',
  'CHAR(1 CHAR)',
  'DATE',
  'TIMESTAMP(6)',
  'TIMESTAMP(6) WITH TIME ZONE',
  'CLOB',
  'BLOB',
  'RAW(16)',
  'BINARY_DOUBLE',
  'JSON'
] as const
const supportedType =
  /^(?:NUMBER(?:\((?:\*|\d{1,2})(?:,-?\d{1,3})?\))?|FLOAT(?:\(\d{1,3}\))?|(?:CHAR|VARCHAR2)\(\d{1,5}(?: (?:CHAR|BYTE))?\)|(?:NCHAR|NVARCHAR2|RAW)\(\d{1,5}\)|TIMESTAMP(?:\([0-9]\))?(?: WITH (?:LOCAL )?TIME ZONE)?|DATE|BINARY_FLOAT|BINARY_DOUBLE|CLOB|NCLOB|BLOB|JSON|BOOLEAN)$/i

const defaultField = (): FieldDefinition => ({
  name: '',
  type: 'VARCHAR2(255 CHAR)',
  nullable: true,
  primary: false,
  autoIncrement: false,
  defaultMode: 'none',
  defaultValue: '',
  comment: '',
  extra: ''
})

const fields = (columns: Column[]): FieldDefinition[] =>
  columns.map((column) => ({
    ...defaultField(),
    originalName: column.name,
    name: column.name,
    type: column.type,
    nullable: column.nullable === 'YES',
    primary: column.key === 'PRI',
    autoIncrement: column.extra.includes('IDENTITY'),
    defaultMode: generated(column) || column.default == null ? 'none' : 'expression',
    defaultValue: generated(column) ? '' : (column.default ?? ''),
    locked: generated(column) || !supportedType.test(column.type),
    extra: column.extra
  }))

function validatedType(field: FieldDefinition) {
  const type = field.type.trim().toUpperCase()
  if (!supportedType.test(type)) throw new Error(`字段 ${field.name} 的类型暂不支持，请使用 SQL 编辑器`)
  return type
}

function defaultValue(field: FieldDefinition): string | undefined {
  if (field.defaultMode === 'none') return undefined
  if (field.defaultMode === 'null') return 'NULL'
  if (field.defaultMode === 'literal') return sqlValue(validatedType(field), field.defaultValue)
  if (/^(?:SYSDATE|SYSTIMESTAMP|CURRENT_DATE|CURRENT_TIMESTAMP)$/i.test(field.defaultValue.trim())) return field.defaultValue.trim().toUpperCase()
  throw new Error('Oracle 默认表达式支持 SYSDATE、SYSTIMESTAMP、CURRENT_DATE 和 CURRENT_TIMESTAMP')
}

function definition(field: FieldDefinition) {
  const type = validatedType(field)
  const value = defaultValue(field)
  if (field.autoIncrement && (!/^NUMBER(?:\(\d+(?:,0)?\))?$/.test(type) || value !== undefined)) {
    throw new Error('Oracle 自增字段必须使用整数 NUMBER，且不能设置默认值')
  }
  return identifier(field.name) + ' ' + type + (field.autoIncrement ? ' GENERATED BY DEFAULT AS IDENTITY' : '') + (value === undefined ? '' : ' DEFAULT ' + value) + (field.nullable ? '' : ' NOT NULL')
}

function identity(target: ObjectTarget, name: string) {
  if (!target.schema) throw new Error('请从目标 schema 下新建表')
  return identifier(target.schema) + '.' + identifier(name)
}

function columnComment(table: string, field: FieldDefinition) {
  return `COMMENT ON COLUMN ${table}.${identifier(field.name)} IS ${field.comment ? textLiteral(field.comment) : "''"}`
}

function sql(action: Action, target: ObjectTarget, values: ObjectFormValues, original: FieldDefinition[]) {
  if (!values.fields.length) throw new Error('表至少需要一个字段')
  const seen = new Set<string>()
  const origins = new Map<string, FieldDefinition>()
  const primary = values.fields.filter((field) => field.primary)
  for (const field of values.fields) {
    identifier(field.name)
    if (seen.has(field.name)) throw new Error(`字段 ${field.name} 重复`)
    seen.add(field.name)
    if (field.primary && field.nullable) throw new Error('主键字段不能允许 NULL')
    if (!field.nullable && field.defaultMode === 'null') throw new Error('非空字段不能设置 NULL 默认值')
    if (field.originalName) {
      if (origins.has(field.originalName) || !original.some((column) => column.originalName === field.originalName)) throw new Error('字段原始标识无效')
      origins.set(field.originalName, field)
    }
  }
  const primaryClause = primary.length ? `PRIMARY KEY (${primary.map((field) => identifier(field.name)).join(', ')})` : ''
  if (action === ObjectAction.CreateTable) {
    const table = identity(target, values.name)
    const definitions = values.fields.map(definition)
    if (primaryClause) definitions.push(primaryClause)
    return [`CREATE TABLE ${table} (\n  ${definitions.join(',\n  ')}\n)`, ...values.fields.filter((field) => field.comment).map((field) => columnComment(table, field))].join(';\n') + ';'
  }
  if (action !== ObjectAction.EditTable) throw new Error('不支持此表操作')
  const table = relation(target.table)
  const statements: string[] = []
  const oldKeys = original.filter((field) => field.primary)
  const keysChanged = JSON.stringify(oldKeys.map((field) => field.name)) !== JSON.stringify(primary.map((field) => field.originalName ?? field.name))
  if (keysChanged && oldKeys.length) statements.push(`ALTER TABLE ${table} DROP PRIMARY KEY`)
  for (const old of original) {
    const field = origins.get(old.name)
    if (old.locked && (!field || (Object.keys(old) as (keyof FieldDefinition)[]).some((key) => old[key] !== field[key]))) {
      throw new Error(`复杂字段 ${old.name} 请使用 SQL 编辑器修改`)
    }
    if (!field) {
      statements.push(`ALTER TABLE ${table} DROP COLUMN ${identifier(old.name)}`)
      continue
    }
    const column = identifier(field.name)
    if (field.name !== old.name) {
      if (original.some((other) => other.name === field.name)) throw new Error(`新字段名 ${field.name} 已存在，请分步重命名`)
      statements.push(`ALTER TABLE ${table} RENAME COLUMN ${identifier(old.name)} TO ${column}`)
    }
    if (field.autoIncrement !== old.autoIncrement) throw new Error('已有字段的自增属性请使用 SQL 编辑器修改')
    const changes = [column]
    if (field.type !== old.type) changes.push(validatedType(field))
    if (field.defaultMode !== old.defaultMode || field.defaultValue !== old.defaultValue) changes.push('DEFAULT ' + (defaultValue(field) ?? 'NULL'))
    if (field.nullable !== old.nullable) changes.push(field.nullable ? 'NULL' : 'NOT NULL')
    if (changes.length > 1) statements.push(`ALTER TABLE ${table} MODIFY (${changes.join(' ')})`)
    if (field.comment !== old.comment) statements.push(columnComment(table, field))
  }
  for (const field of values.fields) {
    if (field.originalName) continue
    statements.push(`ALTER TABLE ${table} ADD (${definition(field)})`)
    if (field.comment) statements.push(columnComment(table, field))
  }
  if (keysChanged && primaryClause) statements.push(`ALTER TABLE ${table} ADD ${primaryClause}`)
  if (!statements.length) throw new Error('表结构没有变化')
  return statements.join(';\n') + ';'
}

export const tableDesign = {
  fieldTypes,
  defaultField,
  initialFields: () => [{ ...defaultField(), name: 'ID', type: 'NUMBER(18,0)', nullable: false, primary: true, autoIncrement: true }],
  fields,
  sql,
  identity,
  sameDefinition: (current, original) => current.trim() === original.trim()
} satisfies TableDesignAdapter
