import type { Column } from '../../../typings/database/index.ts'
import { ObjectAction } from '../../typings/objectManagement/index.ts'
import type { ObjectAction as Action, FieldDefinition, ObjectFormValues, ObjectTarget, TableDesignAdapter } from '../../typings/objectManagement/index.ts'
import { identifier, literal, relation } from '../query/index.ts'

const fieldTypes = [
  'bigint',
  'integer',
  'smallint',
  'numeric',
  'numeric(10,2)',
  'real',
  'double precision',
  'boolean',
  'character varying(255)',
  'text',
  'date',
  'timestamp without time zone',
  'timestamp with time zone',
  'time without time zone',
  'uuid',
  'json',
  'jsonb',
  'bytea'
] as const
const typePattern =
  /^(?:bigint|integer|smallint|numeric(?:\(\d{1,4}(?:,\d{1,4})?\))?|real|double precision|boolean|character varying(?:\(\d{1,6}\))?|varchar(?:\(\d{1,6}\))?|character(?:\(\d{1,6}\))?|text|date|timestamp(?: with(?:out)? time zone)?|time(?: with(?:out)? time zone)?|uuid|jsonb?|bytea)$/i
function name(value: string) {
  if (!value.trim() || value.includes('\0') || new TextEncoder().encode(value).length > 63) throw new Error('名称不能为空，且最多 63 个 UTF-8 字节')
  return identifier(value)
}
const defaultField = (): FieldDefinition => ({ name: '', type: 'text', nullable: true, primary: false, autoIncrement: false, defaultMode: 'none', defaultValue: '', comment: '', extra: '' })
function fieldSQL(field: FieldDefinition) {
  if (!typePattern.test(field.type.trim())) throw new Error(`字段 ${field.name} 的类型暂不支持，请使用 SQL 编辑器`)
  if (field.extra) throw new Error('此字段的额外属性暂不支持设置')
  if (field.primary && field.nullable) throw new Error('主键字段不能允许 NULL')
  if (field.autoIncrement && (!/^(smallint|integer|bigint)$/i.test(field.type.trim()) || field.defaultMode !== 'none')) throw new Error('自增字段必须为整数类型且不能同时设置默认值')
  let sql = `${name(field.name)} ${field.type.trim()}`
  if (field.autoIncrement) sql += ' GENERATED BY DEFAULT AS IDENTITY'
  if (!field.nullable) sql += ' NOT NULL'
  if (field.defaultMode === 'null') {
    if (!field.nullable) throw new Error('非空字段不能设置 NULL 默认值')
    sql += ' DEFAULT NULL'
  } else if (field.defaultMode === 'literal') sql += ` DEFAULT ${literal(field.defaultValue)}`
  else if (field.defaultMode === 'expression') {
    if (!/^CURRENT_TIMESTAMP$/i.test(field.defaultValue)) throw new Error('默认表达式仅支持 CURRENT_TIMESTAMP')
    sql += ' DEFAULT CURRENT_TIMESTAMP'
  }
  return sql
}
function fields(columns: Column[]): FieldDefinition[] {
  return columns.map((column) => ({
    ...defaultField(),
    originalName: column.name,
    name: column.name,
    type: column.type,
    nullable: column.nullable === 'YES',
    primary: column.key === 'PRI',
    autoIncrement: column.extra === 'IDENTITY' || Boolean(column.default && /^nextval\(/i.test(column.default)),
    defaultMode: column.default === null || /^nextval\(/i.test(column.default) ? 'none' : 'expression',
    defaultValue: column.default && !/^nextval\(/i.test(column.default) ? column.default : '',
    comment: column.comment,
    extra: column.extra || (column.default && /^nextval\(/i.test(column.default) ? 'SERIAL' : ''),
    locked: column.extra.includes('GENERATED')
  }))
}
function batch(statements: string[]) {
  if (statements.length === 1) return statements[0] + ';'
  const lines = statements.map((statement) => `  EXECUTE ${literal(statement)};`).join('\n')
  let delimiter = '$sql_studio$'
  while (lines.includes(delimiter)) delimiter = delimiter.slice(0, -1) + '_$'
  return `DO ${delimiter}\nBEGIN\n${lines}\nEND;\n${delimiter};`
}
function defaultSQL(field: FieldDefinition) {
  if (field.defaultMode === 'none') return undefined
  if (field.defaultMode === 'null') return 'NULL'
  if (field.defaultMode === 'literal') return literal(field.defaultValue)
  if (/^CURRENT_TIMESTAMP$/i.test(field.defaultValue)) return 'CURRENT_TIMESTAMP'
  throw new Error('新增或修改的默认表达式仅支持 CURRENT_TIMESTAMP')
}
function identity(target: ObjectTarget, value: string) {
  if (!target.schema) throw new Error('请从目标 schema 下新建表')
  return `${name(target.schema)}.${name(value)}`
}
function sql(action: Action, target: ObjectTarget, values: ObjectFormValues, original: FieldDefinition[]) {
  if (!values.fields.length) throw new Error('表至少需要一个字段')
  const seen = new Set<string>()
  const origins = new Set<string>()
  for (const field of values.fields) {
    name(field.name)
    if (seen.has(field.name)) throw new Error(`字段 ${field.name} 重复`)
    if (field.primary && field.nullable) throw new Error('主键字段不能允许 NULL')
    if (field.defaultMode === 'null' && !field.nullable) throw new Error('非空字段不能设置 NULL 默认值')
    if (field.originalName) {
      if (origins.has(field.originalName)) throw new Error('字段原始标识重复')
      origins.add(field.originalName)
    }
    seen.add(field.name)
  }
  if (action === ObjectAction.CreateTable) {
    const clauses = values.fields.map(fieldSQL)
    const primary = values.fields.filter((field) => field.primary).map((field) => name(field.name))
    if (primary.length) clauses.push(`PRIMARY KEY (${primary.join(', ')})`)
    const table = identity(target, values.name)
    const statements = [`CREATE TABLE ${table} (\n  ${clauses.join(',\n  ')}\n)`]
    for (const field of values.fields) if (field.comment) statements.push(`COMMENT ON COLUMN ${table}.${name(field.name)} IS ${literal(field.comment)}`)
    return batch(statements)
  }
  if (action !== ObjectAction.EditTable) throw new Error('不支持此表操作')
  const table = relation(target.table)
  const statements: string[] = []
  const matched = new Set<string>()
  const primaryBefore = original.filter((field) => field.primary).map((field) => field.originalName)
  const primaryAfter = values.fields.filter((field) => field.primary).map((field) => field.originalName || field.name)
  const primaryChanged = JSON.stringify(primaryBefore) !== JSON.stringify(primaryAfter)
  const dropPrimary = primaryChanged && primaryBefore.length > 0
  if (dropPrimary) {
    // 固定 SQL 查询真实主键名称，quote_ident 避免将目录名称拼入 SQL。
    statements.push(`ALTER TABLE ${table} DROP CONSTRAINT `)
  }
  for (const old of original) {
    const current = values.fields.find((field) => field.originalName === old.originalName)
    if (!current) {
      if (old.locked) throw new Error(`生成字段 ${old.name} 暂不支持删除`)
      statements.push(`ALTER TABLE ${table} DROP COLUMN ${name(old.name)}`)
      continue
    }
    if (matched.has(current.originalName!)) throw new Error('字段原始标识重复')
    matched.add(current.originalName!)
    if (old.locked && (Object.keys(old) as (keyof FieldDefinition)[]).some((key) => current[key] !== old[key])) throw new Error(`生成字段 ${old.name} 暂不支持修改`)
    if (current.name !== old.name) {
      if (original.some((field) => field.name === current.name)) throw new Error(`新字段名 ${current.name} 已存在，请分步重命名`)
      statements.push(`ALTER TABLE ${table} RENAME COLUMN ${name(old.name)} TO ${name(current.name)}`)
    }
    const column = name(current.name)
    if (current.type !== old.type) {
      if (!typePattern.test(current.type.trim())) throw new Error(`字段 ${current.name} 的类型暂不支持`)
      statements.push(`ALTER TABLE ${table} ALTER COLUMN ${column} TYPE ${current.type.trim()}`)
    }
    if (current.nullable !== old.nullable && !(current.primary && primaryChanged)) statements.push(`ALTER TABLE ${table} ALTER COLUMN ${column} ${current.nullable ? 'DROP' : 'SET'} NOT NULL`)
    if (current.autoIncrement !== old.autoIncrement) {
      if (current.autoIncrement) {
        if (!/^(smallint|integer|bigint)$/i.test(current.type.trim()) || current.defaultMode !== 'none') throw new Error('自增字段必须为整数类型且不能同时设置默认值')
        if (old.defaultMode !== 'none') statements.push(`ALTER TABLE ${table} ALTER COLUMN ${column} DROP DEFAULT`)
        statements.push(`ALTER TABLE ${table} ALTER COLUMN ${column} ADD GENERATED BY DEFAULT AS IDENTITY`)
      } else statements.push(`ALTER TABLE ${table} ALTER COLUMN ${column} ${old.extra === 'IDENTITY' ? 'DROP IDENTITY' : 'DROP DEFAULT'}`)
    }
    if (current.defaultMode !== old.defaultMode || current.defaultValue !== old.defaultValue) {
      if (current.autoIncrement) throw new Error('自增字段不能设置默认值')
      const value = defaultSQL(current)
      statements.push(`ALTER TABLE ${table} ALTER COLUMN ${column} ${value === undefined ? 'DROP DEFAULT' : 'SET DEFAULT ' + value}`)
    }
    if (current.comment !== old.comment) statements.push(`COMMENT ON COLUMN ${table}.${column} IS ${current.comment ? literal(current.comment) : 'NULL'}`)
  }
  for (const field of values.fields) {
    if (field.originalName) {
      if (!matched.has(field.originalName)) throw new Error('字段原始标识无效')
      continue
    }
    statements.push(`ALTER TABLE ${table} ADD COLUMN ${fieldSQL(field)}`)
    if (field.comment) statements.push(`COMMENT ON COLUMN ${table}.${name(field.name)} IS ${literal(field.comment)}`)
  }
  if (primaryChanged && primaryAfter.length)
    statements.push(
      `ALTER TABLE ${table} ADD PRIMARY KEY (${values.fields
        .filter((field) => field.primary)
        .map((field) => name(field.name))
        .join(', ')})`
    )
  if (!statements.length) throw new Error('表结构没有变化')
  if (!dropPrimary) return batch(statements)
  const lines = statements.map((statement, index) => (index === 0 ? `  EXECUTE ${literal(statement)} || quote_ident(primary_name);` : `  EXECUTE ${literal(statement)};`)).join('\n')
  let delimiter = '$sql_studio$'
  while (lines.includes(delimiter)) delimiter = delimiter.slice(0, -1) + '_$'
  return `DO ${delimiter}\nDECLARE primary_name text;\nBEGIN\n  SELECT conname INTO STRICT primary_name FROM pg_catalog.pg_constraint WHERE conrelid = ${literal(table)}::regclass AND contype = 'p';\n${lines}\nEND;\n${delimiter};`
}
export const tableDesign: TableDesignAdapter = {
  fieldTypes,
  defaultField,
  initialFields: () => [{ ...defaultField(), name: 'id', type: 'bigint', nullable: false, primary: true, autoIncrement: true }],
  fields,
  sql,
  identity,
  sameDefinition: (current, original) => current === original
}
